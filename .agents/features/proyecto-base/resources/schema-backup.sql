-- ============================================================================
--  schema-backup.sql
--  Sistema de Reserva de Libros para una Biblioteca - backend
-- ----------------------------------------------------------------------------
--  DDL de las 5 tablas que Hibernate crea con `ddl-auto: update`.
--  Se ejecuta a mano para reconstruir el esquema en una base vacia, sin
--  arrancar la aplicacion.
--
--  Uso:
--    psql "postgresql://postgres:postgres@127.0.0.1:54322/postgres" -f schema-backup.sql
--
--  Nota: los nombres de las restricciones UNIQUE que genera Hibernate son un
--  hash (uk...); aqui se escriben con nombres legibles y estables.
-- ============================================================================

CREATE TABLE categoria (
    id_categoria integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nombre       varchar(100) NOT NULL,
    descripcion  varchar(200) NOT NULL,
    estado       boolean NOT NULL,
    CONSTRAINT categoria_pkey PRIMARY KEY (id_categoria)
);

CREATE TABLE cliente (
    id_cliente integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nombres    varchar(100) NOT NULL,
    apellidos  varchar(100) NOT NULL,
    cedula     varchar(15)  NOT NULL,
    email      varchar(100) NOT NULL,
    CONSTRAINT cliente_pkey PRIMARY KEY (id_cliente),
    CONSTRAINT uk_cliente_cedula UNIQUE (cedula),
    CONSTRAINT uk_cliente_email  UNIQUE (email)
);

CREATE TABLE libro (
    id_libro     integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    titulo       varchar(150) NOT NULL,
    autor        varchar(100) NOT NULL,
    isbn         varchar(20)  NOT NULL,
    disponible   boolean NOT NULL,
    id_categoria integer NOT NULL,
    CONSTRAINT libro_pkey PRIMARY KEY (id_libro),
    CONSTRAINT uk_libro_isbn UNIQUE (isbn),
    CONSTRAINT fk_libro_categoria FOREIGN KEY (id_categoria) REFERENCES categoria (id_categoria)
);

CREATE TABLE reserva (
    id_reserva     integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    fecha_reserva  timestamp(6) without time zone NOT NULL,
    id_cliente     integer NOT NULL,
    CONSTRAINT reserva_pkey PRIMARY KEY (id_reserva),
    CONSTRAINT fk_reserva_cliente FOREIGN KEY (id_cliente) REFERENCES cliente (id_cliente)
);

CREATE TABLE detalle_reserva (
    id_detalle  integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_reserva  integer NOT NULL,
    id_libro    integer NOT NULL,
    CONSTRAINT detalle_reserva_pkey PRIMARY KEY (id_detalle),
    CONSTRAINT fk_detalle_reserva FOREIGN KEY (id_reserva) REFERENCES reserva (id_reserva),
    CONSTRAINT fk_detalle_libro   FOREIGN KEY (id_libro)   REFERENCES libro (id_libro)
);

-- ============================================================================
--  Relaciones
--    categoria 1 ---< N libro
--    cliente   1 ---< N reserva 1 ---< N detalle_reserva N >--- 1 libro
-- ============================================================================
